import path from 'node:path';
import { read as open } from 'xlsx';
import { localFilesConfigSchema } from 'librechat-data-provider';
import { createLocalFilesReader } from './reader';
import { createLocalFilesWriter } from './writer';

const config = localFilesConfigSchema.parse({});
const write = createLocalFilesWriter(
  path.join(__dirname, '../../dist/filesystem/writer-worker.cjs'),
);
const read = createLocalFilesReader(
  path.join(__dirname, '../../dist/filesystem/reader-worker.cjs'),
);
const signal = new AbortController().signal;

it.each([
  ['pdf', 'Document generation verified'],
  ['docx', 'Document generation verified'],
  ['odt', 'Document generation verified & <escaped>'],
  ['xlsx', 'Name,Value\nDocument generation verified,42'],
  ['xls', 'Name,Value\nDocument generation verified,42'],
  ['ods', 'Name,Value\nDocument generation verified,42'],
  ['pptx', 'Title\nDocument generation verified\n---\nSecond slide\nMore text'],
  ['odp', 'Title\nDocument generation verified\n---\nSecond slide\nMore text'],
])(
  'creates a real %s document that the existing reader can open',
  async (extension, content) => {
    const filename = `generated.${extension}`;
    const result = await write({
      input: { operation: 'write', path: filename, content },
      config,
      signal,
    });
    expect(result.ok).toBe(true);
    if (!result.ok || !result.value.binary) throw new Error('No generated bytes');
    const data = Buffer.from(result.value.binary.data, 'base64');
    const signatures: Record<string, string> = { pdf: '25504446', xls: 'd0cf11e0' };
    expect(data.subarray(0, 4).toString('hex')).toBe(signatures[extension] ?? '504b0304');
    const extracted = await read({
      input: { operation: 'read', path: filename },
      data,
      config,
      signal,
    });
    expect(extracted).toMatchObject({
      ok: true,
      value: { content: expect.stringContaining('Document generation verified') },
    });
  },
  30000,
);

it('keeps structured sheet values literal and preserves Unicode and multiple sheets', async () => {
  const content = JSON.stringify({
    sheets: [
      {
        name: 'Values',
        rows: [
          ['Name', 'Value'],
          ['سلام', 42],
          ['=HYPERLINK("https://invalid")', false],
        ],
      },
      { name: 'Other', rows: [['Second sheet']] },
    ],
  });
  const result = await write({
    input: { operation: 'write', path: 'values.xlsx', content },
    config,
    signal,
  });
  expect(result.ok).toBe(true);
  if (!result.ok || !result.value.binary) throw new Error('No spreadsheet');
  const book = open(Buffer.from(result.value.binary.data, 'base64'), { type: 'buffer' });
  expect(book.SheetNames).toEqual(['Values', 'Other']);
  expect(book.Sheets.Values.A2.v).toBe('سلام');
  expect(book.Sheets.Values.B2.v).toBe(42);
  expect(book.Sheets.Values.A3.f).toBeUndefined();
});

it('rejects invalid structured content and configured output/page limits without returning diagnostics', async () => {
  const input = {
    operation: 'write' as const,
    path: 'private.xlsx',
    content: '{"password":"private-secret"}',
  };
  expect(await write({ input, config, signal })).toEqual({
    ok: false,
    error: { code: 'INVALID_REQUEST' },
  });
  expect(
    await write({
      input: { ...input, path: 'small.pdf', content: 'Hello' },
      config: { ...config, maxFileBytes: 10 },
      signal,
    }),
  ).toEqual({ ok: false, error: { code: 'TOO_LARGE' } });
  expect(
    await write({
      input: { ...input, path: 'pages.pdf', content: 'First\fSecond' },
      config: { ...config, maxPages: 1 },
      signal,
    }),
  ).toEqual({ ok: false, error: { code: 'TOO_LARGE' } });
});

it('cancels before starting document generation and handles the next request normally', async () => {
  const input = { operation: 'write' as const, path: 'cancelled.docx', content: 'Cancelled' };
  expect(await write({ input, config, signal: AbortSignal.abort() })).toEqual({
    ok: false,
    error: { code: 'CANCELLED' },
  });
  expect((await write({ input, config, signal })).ok).toBe(true);
});
